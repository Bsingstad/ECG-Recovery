"""Patient-specific dipole factor analysis with missing data.

Physiology
----------
To first order the body surface ECG is generated by one time-varying current
dipole, the heart vector ``h(t)`` (3 components). Every lead is a fixed linear
projection of it (the lead field), plus a small non-dipolar part::

    x(t) = mu + W h(t) + e(t),        x = [I, II, V1, ..., V6]  (8 leads)

``W`` (8 x K) is the *patient's* lead-field matrix. It depends on the
torso geometry, the position of the heart and the electrode placement, so it
differs from the textbook Dower matrix and from patient to patient. ``e(t)``
is the lead-specific residual (local potentials, noise) with variance
``psi_j`` per lead.

In the printed paper layout every independent lead is observed in at least one
quarter *together with* the rhythm leads II, V1 and V5, which roughly span the
three dipole axes (Y, Z, X). The record therefore contains enough information
to estimate its own lead field: a missing lead's loading row is identified
from the quarter in which that lead *was* recorded, and is then used to
predict it in the quarters where it was not.

Mathematics
-----------
Factor analysis model for one record, ``h ~ N(0, I_K)``,
``e ~ N(0, diag(psi))``, fitted by EM on all observed samples with the
standard missing-data E-step. Samples fall into a handful of observation
patterns (three for the paper layout), so the E-step works on per-pattern
sufficient statistics ``S_p = sum_t z_o z_o^T`` and the cost of an EM
iteration does not depend on the record length:

* E-step (pattern ``p`` with observed set ``o``)::

      Sigma_p = (I + W_o^T Psi_o^-1 W_o)^-1,   G_p = Sigma_p W_o^T Psi_o^-1
      E[h_t] = G_p z_o(t)
      sum_t E[h h^T] = n_p Sigma_p + G_p S_p G_p^T

* M-step (row ``j`` of ``W``, only patterns in which lead ``j`` is observed)
  with a conjugate Gaussian prior ``w_j ~ N(m_j, psi_j / tau I)``::

      w_j = (b_j + tau m_j) (A_j + tau I)^-1
      psi_j = (s_jj - 2 w_j b_j^T + w_j A_j w_j^T
               + tau |w_j - m_j|^2 + nu psi0_j) / (n_j + nu)

  where ``A_j = sum_p sum_t E[h h^T]``, ``b_j = sum_p (S_p G_p^T)[j]`` and
  ``s_jj = sum_p S_p[j, j]``. ``nu psi0_j`` is an inverse-gamma prior on the
  residual variance.

* Prior centre. ``W_pop`` is a population lead field learned in :meth:`fit`
  by factor analysis of the training ECGs (rotated to the Dower axes for
  interpretability). Because ``h`` is latent, a patient-specific heart
  orientation and dipole size correspond to ``W = W_pop A`` with an arbitrary
  K x K matrix ``A``. With ``align="linear"`` the prior centre is
  ``M = W_pop A*`` where ``A*`` is the least-squares fit of ``W`` onto
  ``W_pop``, re-estimated every iteration. The prior therefore only penalises
  the part of the patient lead field outside the population's lead-field
  subspace ("population torso, patient-specific heart"); ``tau -> inf``
  gives a dipole model with population lead field and patient dipole
  covariance, ``tau -> 0`` a free patient factor analysis.

* Prediction: the conditional mean ``E[x_m | x_o] = mu_m + W_m G_p z_o``.

Baseline wander
---------------
Raw PTB-XL contains baseline wander, and offsets differ per quarter. Before
fitting, a slowly varying baseline is removed from each lead within each
segment of constant observation pattern (default: two-stage moving median,
the classic 200 ms / 600 ms baseline estimator). The factor model is fitted
on, and predicts, the baseline-free signal. A missing lead's level is set to
the median of its own observed raw samples.

Empirical notes (PTB-XL validation fold): wander in a missing lead is almost
unpredictable from the wander of the rhythm leads (population R^2 < 0.03),
and continuing the adjacent observed baseline is worse than the median. On
baseline-free signals the fitted patient model is as accurate as a linear map
fitted on the missing quarter's own ground truth (an oracle), so most of the
remaining pooled error is baseline wander and artefacts in the ground truth.
The moving median also removes some genuine low-frequency cardiac content
(ST level, T-wave tails) from the inputs; on real data that costs less than
the wander it removes (it beats a segment median and Butterworth high-pass).
"""

from __future__ import annotations

from functools import lru_cache

import numpy as np
from scipy.ndimage import median_filter
from scipy.signal import butter, sosfiltfilt

from ..leads import INDEPENDENT_LEADS, independent_from_12, lead_matrix
from .base import Reconstructor

_FS = 500.0


# --------------------------------------------------------------------------
# Baseline handling
# --------------------------------------------------------------------------
@lru_cache(maxsize=8)
def _highpass_sos(fc: float, fs: float) -> np.ndarray:
    return butter(2, fc, btype="highpass", fs=fs, output="sos")


def _segments(m8: np.ndarray) -> list[tuple[int, int]]:
    """Contiguous ``[start, stop)`` runs of identical observation pattern."""
    change = np.flatnonzero(np.any(m8[1:] != m8[:-1], axis=1)) + 1
    edges = np.r_[0, change, len(m8)]
    return [(int(a), int(b)) for a, b in zip(edges[:-1], edges[1:])]


def _baseline_1d(x: np.ndarray, mode: str, fs: float = _FS) -> np.ndarray:
    """Baseline estimate of a 1-D, fully observed signal segment.

    ``mode`` is ``"median"`` (constant segment median), ``"movmedian"``
    (two-stage moving median) or ``"highpass<f>"``, e.g. ``"highpass0.5"``:
    the low-pass complement of a zero-phase 2nd-order Butterworth high-pass
    with cut-off ``f`` Hz, plus the median of the high-passed signal (so that
    the isoelectric level, not the mean, maps to zero).
    """
    if mode == "median":
        return np.full_like(x, np.median(x))
    if mode.startswith("highpass"):
        fc = float(mode[len("highpass"):] or 0.5)
        sos = _highpass_sos(fc, fs)
        if len(x) <= 3 * (2 * len(sos) + 1):
            return np.full_like(x, np.median(x))
        hp = sosfiltfilt(sos, x - np.median(x))
        return x - hp + np.median(hp)
    if mode == "movmedian":
        # Two-stage moving median (200 ms removes QRS, 600 ms removes P/T),
        # computed on a block-averaged 100 Hz copy for speed: the baseline
        # is far below 50 Hz, so nothing relevant is lost.
        q = max(int(round(fs / 100.0)), 1)
        nb = len(x) // q
        if nb < int(0.6 * fs / q) + 1:
            return np.full_like(x, np.median(x))
        xd = x[: nb * q].reshape(nb, q).mean(axis=1)
        w1 = int(round(0.2 * fs / q)) | 1
        w2 = int(round(0.6 * fs / q)) | 1
        bd = median_filter(median_filter(xd, size=w1, mode="nearest"), size=w2, mode="nearest")
        centres = (np.arange(nb) + 0.5) * q - 0.5
        return np.interp(np.arange(len(x)), centres, bd)
    raise ValueError(f"unknown baseline mode {mode!r}")


def remove_baseline(x8: np.ndarray, m8: np.ndarray, mode: str) -> np.ndarray:
    """Baseline-free copy of ``x8`` (0 where unobserved). The baseline is
    estimated separately for each lead in each segment of constant pattern,
    so per-quarter offsets of the printed layout are removed."""
    z = np.zeros_like(x8, dtype=float)
    for a, b in _segments(m8):
        for j in np.flatnonzero(m8[a]):
            seg = x8[a:b, j]
            z[a:b, j] = seg - _baseline_1d(seg, mode)
    return z


def missing_levels(
    x8: np.ndarray, base: np.ndarray, m8: np.ndarray, tc: float, fs: float = _FS
) -> np.ndarray:
    """Baseline level ``(n, 8)`` assigned to every sample of every lead.

    The dipole model says nothing about baseline wander, so a missing lead's
    level is extrapolated from its own observations: the observed baseline
    ``base`` is continued from the nearest observed sample (linearly
    interpolated across interior gaps) and relaxes towards the lead's overall
    median with time constant ``tc`` seconds (``tc=0``: median only,
    ``tc=inf``: pure continuation). Wander behaves partly like a random walk
    (favouring continuation) and partly mean-reverting (favouring the median).
    """
    n = len(x8)
    t = np.arange(n)
    out = np.zeros((n, 8))
    for j in range(8):
        obs = np.flatnonzero(m8[:, j])
        if obs.size == 0:
            continue
        med = np.median(x8[obs, j])
        if tc <= 0:
            out[:, j] = med
            continue
        cont = np.interp(t, obs, base[obs, j])
        pos = np.searchsorted(obs, t).clip(1, obs.size - 1)
        dist = np.minimum(np.abs(t - obs[pos - 1]), np.abs(t - obs[pos])) / fs
        w = np.exp(-dist / tc) if np.isfinite(tc) else np.ones(n)
        out[:, j] = w * cont + (1 - w) * med
    return out


# --------------------------------------------------------------------------
# Factor analysis helpers
# --------------------------------------------------------------------------
def observation_patterns(m8: np.ndarray) -> list[tuple[np.ndarray, np.ndarray]]:
    """Group samples by observation pattern: list of ``(pattern, rows)``."""
    code = m8.astype(np.int64) @ (1 << np.arange(m8.shape[1], dtype=np.int64))
    out = []
    for c in np.unique(code):
        rows = np.flatnonzero(code == c)
        out.append((m8[rows[0]].copy(), rows))
    return out


def fa_from_covariance(C: np.ndarray, k: int, n_iter: int = 500, tol: float = 1e-9):
    """Maximum-likelihood factor analysis of a covariance matrix ``C``
    (fully observed data). Returns ``(W, psi)`` with ``C ~ W W^T + diag(psi)``."""
    d = C.shape[0]
    evals, evecs = np.linalg.eigh(C)
    order = np.argsort(evals)[::-1][:k]
    W = evecs[:, order] * np.sqrt(np.maximum(evals[order], 1e-12))
    psi = np.maximum(np.diag(C) - (W ** 2).sum(1), 1e-3 * np.diag(C))
    prev = -np.inf
    for _ in range(n_iter):
        Sig = np.linalg.inv(W @ W.T + np.diag(psi))
        G = W.T @ Sig                                      # (k, d)
        Ehh = np.eye(k) - G @ W + G @ C @ G.T
        W = C @ G.T @ np.linalg.inv(Ehh)
        psi = np.maximum(np.diag(C - W @ G @ C), 1e-6 * np.diag(C))
        _, logdet = np.linalg.slogdet(W @ W.T + np.diag(psi))
        ll = -logdet - np.trace(np.linalg.solve(W @ W.T + np.diag(psi), C))
        if abs(ll - prev) < tol:
            break
        prev = ll
    return W, psi


def procrustes_to_dower(W: np.ndarray) -> np.ndarray:
    """Rotate factor loadings ``W`` (8 x K) so that the first three factors
    align with the Dower X, Y, Z axes. Orthogonal rotations leave the factor
    model (and every prediction) unchanged; this is for interpretability."""
    k = W.shape[1]
    target = np.zeros((W.shape[0], k))
    target[:, : min(3, k)] = lead_matrix(INDEPENDENT_LEADS)[:, : min(3, k)]
    U, _, Vt = np.linalg.svd(W.T @ target)
    return W @ (U @ Vt)


class PatientFactorAnalysis(Reconstructor):
    """Patient-specific dipole factor analysis (MAP-EM with missing data).

    Parameters
    ----------
    n_factors : int
        Latent dimension K (3 = single dipole).
    tau : float
        Prior strength on the lead-field rows, in pseudo-samples (500 = 1 s).
        The prior variance of ``w_j`` is ``psi_j / tau``.
    nu : float
        Prior strength (pseudo-samples) of the inverse-gamma prior on the
        residual variances ``psi_j``.
    align : {"linear", "none"}
        Prior centre: ``W_pop A`` with patient-specific ``A`` re-fitted each
        iteration ("linear") or the fixed ``W_pop`` scaled to the record's
        amplitude ("none").
    baseline : {"movmedian", "median", "highpass<f>"}
        Baseline removal applied per lead and per observation segment, see
        :func:`_baseline_1d`.
    level_tc : float
        Time constant (s) with which a missing lead's level relaxes from the
        continuation of its nearest observed baseline to its overall median
        (0 = median only), see :func:`missing_levels`.
    n_iter : int
        Maximum number of EM iterations.
    """

    name = "patient_fa"

    def __init__(
        self,
        n_factors: int = 3,
        tau: float = 50.0,
        nu: float = 50.0,
        align: str = "linear",
        baseline: str = "movmedian",
        level_tc: float = 0.0,
        n_iter: int = 100,
        tol: float = 1e-6,
    ):
        self.n_factors = int(n_factors)
        self.tau = float(tau)
        self.nu = float(nu)
        self.align = align
        self.baseline = baseline
        self.level_tc = float(level_tc)
        self.n_iter = int(n_iter)
        self.tol = float(tol)
        self.W_pop: np.ndarray | None = None
        self.psi_ratio_pop: np.ndarray | None = None

    # ------------------------------------------------------------------
    def fit(self, train_ecgs: np.ndarray | None = None) -> "PatientFactorAnalysis":
        """Learn the population lead field ``W_pop`` by factor analysis of the
        (baseline-removed) training ECGs. Without training data the Dower
        matrix is used as prior centre."""
        k = self.n_factors
        if train_ecgs is None:
            L8 = lead_matrix(INDEPENDENT_LEADS)
            W = np.zeros((8, k))
            W[:, : min(3, k)] = L8[:, : min(3, k)]
            self.W_pop = W
            self.psi_ratio_pop = np.full(8, 0.1)
            return self
        x = independent_from_12(np.asarray(train_ecgs, dtype=np.float64))
        full = np.ones(x.shape[1:], dtype=bool)
        C = np.zeros((8, 8))
        for rec in x:
            z = remove_baseline(rec, full, self.baseline)
            # Normalise each record so that large-amplitude ECGs do not
            # dominate the population lead-field shape.
            z = z / np.sqrt(np.mean(z ** 2) + 1e-12)
            C += z.T @ z / len(z)
        C /= len(x)
        W, psi = fa_from_covariance(C, k)
        self.W_pop = procrustes_to_dower(W)
        self.psi_ratio_pop = psi / np.diag(C)
        return self

    # ------------------------------------------------------------------
    def _prior_centre(self, W: np.ndarray, scale: float) -> np.ndarray:
        if self.align == "linear":
            A, *_ = np.linalg.lstsq(self.W_pop, W, rcond=None)
            return self.W_pop @ A
        if self.align == "none":
            return self.W_pop * scale
        raise ValueError(f"unknown align {self.align!r}")

    def fit_record(self, z: np.ndarray, m8: np.ndarray):
        """MAP-EM for one record. ``z`` is baseline-free (0 where unobserved).

        Returns ``(W, psi, patterns)`` where ``patterns`` is a list of
        ``(observed_bool, rows)``.
        """
        if self.W_pop is None:
            self.fit(None)
        d, k = 8, self.n_factors
        patterns = observation_patterns(m8)
        stats = []
        for pat, rows in patterns:
            if pat.any():
                zo = z[np.ix_(rows, np.flatnonzero(pat))]
                stats.append((pat, len(rows), zo.T @ zo))

        n_j = np.zeros(d)
        s_jj = np.zeros(d)
        for pat, n_p, S_p in stats:
            n_j[pat] += n_p
            s_jj[pat] += np.diag(S_p)
        var_j = np.where(n_j > 0, s_jj / np.maximum(n_j, 1), 0.0)
        var_floor = 1e-4 * max(var_j.max(), 1e-8) + 1e-8
        var_j = np.maximum(var_j, var_floor)

        # Prior on psi: population uniqueness ratio times the record's own
        # observed lead variance (scale-free).
        psi0 = self.psi_ratio_pop * var_j
        # Amplitude scale of the record relative to the population prior.
        pop_var = (self.W_pop ** 2).sum(1) / np.maximum(1 - self.psi_ratio_pop, 1e-3)
        scale = np.sqrt(np.sum(var_j) / np.sum(pop_var))
        W = self.W_pop * scale
        psi = psi0.copy()
        # A tiny ridge keeps the M-step well posed for leads that are never
        # observed when tau = 0 (their row then stays at the prior centre).
        tau, nu = max(self.tau, 1e-6), self.nu
        psi_floor = 1e-3 * var_j
        eye = np.eye(k)
        prev = None
        for _ in range(self.n_iter):
            A = np.zeros((d, k, k))
            b = np.zeros((d, k))
            for pat, n_p, S_p in stats:
                Wo = W[pat]
                B = Wo.T / psi[pat]                               # (k, |o|)
                Sig = np.linalg.inv(np.eye(k) + B @ Wo)
                G = Sig @ B                                       # (k, |o|)
                SG = S_p @ G.T                                    # (|o|, k)
                Ehh = n_p * Sig + G @ SG
                A[pat] += Ehh
                b[pat] += SG
            M = self._prior_centre(W, scale)
            W_new = np.linalg.solve(A + tau * eye, (b + tau * M)[..., None])[..., 0]
            r = (s_jj - 2 * np.einsum("jk,jk->j", W_new, b)
                 + np.einsum("jk,jkl,jl->j", W_new, A, W_new)
                 + tau * ((W_new - M) ** 2).sum(1) + nu * psi0)
            denom = n_j + nu
            psi = np.where(denom > 0, r / np.maximum(denom, 1e-12), psi0)
            psi = np.maximum(psi, psi_floor)
            delta = np.max(np.abs(W_new - W)) / (np.max(np.abs(W)) + 1e-12)
            W = W_new
            if prev is not None and delta < self.tol:
                break
            prev = delta
        return W, psi, patterns

    # ------------------------------------------------------------------
    def predict_independent(self, x8: np.ndarray, m8: np.ndarray) -> np.ndarray:
        m8 = np.asarray(m8, dtype=bool)
        x8 = np.where(m8, x8, 0.0)
        z = remove_baseline(x8, m8, self.baseline)
        W, psi, patterns = self.fit_record(z, m8)

        est = missing_levels(x8, x8 - z, m8, self.level_tc)
        k = W.shape[1]
        for pat, rows in patterns:
            if not pat.any() or pat.all():
                continue
            Wo = W[pat]
            B = Wo.T / psi[pat]
            G = np.linalg.solve(np.eye(k) + B @ Wo, B)
            Eh = z[np.ix_(rows, np.flatnonzero(pat))] @ G.T
            miss = np.flatnonzero(~pat)
            est[np.ix_(rows, miss)] += Eh @ W[miss].T
        return np.nan_to_num(est, nan=0.0, posinf=0.0, neginf=0.0)
